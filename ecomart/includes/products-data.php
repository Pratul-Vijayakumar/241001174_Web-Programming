// Helper functions for product fetching
function getAllProducts() {
    global $products;
    return $products;
}

function getProductById($id) {
    global $products;
    $id = (int)$id;
    return isset($products[$id]) ? $products[$id] : null;
}

function getFeaturedProducts() {
    global $products;
    return array_filter($products, function($p) {
        return !empty($p['featured']);
    });
}

function getCategories() {
    global $products;
    $cats = [];
    foreach ($products as $p) {
        $cats[$p['category']] = isset($cats[$p['category']]) ? $cats[$p['category']] + 1 : 1;
    }
    return $cats;
}

function getRelatedProducts($currentId, $limit = 4) {
    global $products;
    $current = getProductById($currentId);
    if (!$current) return [];
    
    $related = [];
    foreach ($products as $p) {
        if ($p['id'] !== $current['id'] && $p['category'] === $current['category']) {
            $related[] = $p;
        }
    }
    
    // If not enough in same category, pad with other products
    if (count($related) < $limit) {
        foreach ($products as $p) {
            if ($p['id'] !== $current['id'] && !in_array($p, $related)) {
                $related[] = $p;
                if (count($related) >= $limit) break;
            }
        }
    }
    
    return array_slice($related, 0, $limit);
}
